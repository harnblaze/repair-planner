/**
 * Кэш подписанных ссылок на файлы Storage.
 *
 * Зачем: открытая панель чата опрашивает `loadMessagesAction` раз в 15–30
 * секунд, а `signAttachments` на каждый вызов заново подписывал все вложения.
 * Supabase выдаёт новый токен в URL, значит `<img src>` каждый раз менялся, и
 * браузер честно скачивал те же фотографии заново. На проде это дало 7 504 GET
 * картинок чата в сутки при 13 вложениях (≈6 МБ) и 24 ГБ egress за период.
 *
 * Почему это безопасно: в кэше лежат только уже выданные ссылки на конкретные
 * пути. Сами пути берутся из строк, которые прошли RLS проекта, то есть доступ
 * проверен ДО подписи; кэш не расширяет права и ничего не подписывает сам — он
 * лишь переиспользует подпись для того же объекта, пока та ещё действует.
 *
 * Кэш живёт в памяти процесса (Next может держать несколько инстансов). Это
 * оптимизация трафика, а не источник истины: промах кэша стоит одного запроса
 * к Storage, и результат всё равно верный.
 */

/**
 * Запас к истечению ссылки: клиент не должен получить ссылку, которая умрёт у
 * него на глазах, пока он листает чат. 10 минут — с большим перебором для
 * подписи на час.
 */
const EXPIRY_RESERVE_SECONDS = 600;

/**
 * Потолок размера. Записей в проекте единицы-десятки, но кэш общий на процесс
 * и живёт между запросами, поэтому ограничиваем: 500 путей — это мегабайты
 * памяти в худшем случае, и то едва ли.
 */
const MAX_ENTRIES = 500;

type CacheEntry = {
  url: string;
  /** Момент (ms), после которого ссылку отдавать нельзя. */
  expiresAt: number;
};

const cache = new Map<string, CacheEntry>();

/** Ссылка из кэша или null, если её нет либо срок вышел. */
export function getCachedSignedUrl(key: string): string | null {
  const entry = cache.get(key);
  if (!entry) return null;

  if (entry.expiresAt <= Date.now()) {
    cache.delete(key);
    return null;
  }

  return entry.url;
}

/**
 * Запомнить выданную ссылку. Хранится `ttlSeconds` минус запас: ближе к концу
 * срока подпись перестаёт быть надёжной, и лучше подписать заново.
 */
export function rememberSignedUrl(key: string, url: string, ttlSeconds: number): void {
  const lifetimeSeconds = ttlSeconds - EXPIRY_RESERVE_SECONDS;
  // Слишком короткий TTL: кэшировать нечего, ссылка истечёт раньше, чем
  // клиент успеет её показать.
  if (lifetimeSeconds <= 0) return;

  if (!cache.has(key) && cache.size >= MAX_ENTRIES) {
    // Вытеснение простое — очистка целиком. LRU на 500 элементов дал бы
    // выигрыш в считанные промахи, а кода и багов добавил бы заметно больше:
    // промах здесь стоит одного запроса к Storage.
    cache.clear();
  }

  cache.set(key, { url, expiresAt: Date.now() + lifetimeSeconds * 1000 });
}

/** Сбросить кэш — для тестов и на случай, если понадобится ручная инвалидация. */
export function clearSignedUrlCache(): void {
  cache.clear();
}
